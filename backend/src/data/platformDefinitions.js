export function detectPlatformFromUrl(rawUrl, platformsList = PLATFORM_DEFINITIONS) {
  let parsed;
  try {
    parsed = new URL(String(rawUrl || ''));
  } catch {
    return null;
  }
  const host = parsed.hostname.toLowerCase().replace(/^www\./, '');
  let best = null;
  for (const platform of platformsList) {
    for (const domain of platform.domains || []) {
      const clean = String(domain).toLowerCase().replace(/^www\./, '');
      const hostPart = clean.split('/')[0];
      if (clean.includes('/')) {
        if (`${host}${parsed.pathname}`.includes(clean)) {
          best = platform;
          break;
        }
        continue;
      }
      if (host === hostPart || host.endsWith(`.${hostPart}`)) {
        if (!best) best = platform;
      }
    }
    if (best && best.id === platform.id) return platform;
  }
  return best;
}
